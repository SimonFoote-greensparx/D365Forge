#!/usr/bin/env python3
"""Emit references/sources.md into each skill a source serves, and the index at docs/SOURCES.md. --check verifies."""
import collections
from _common import sources, skills, write_or_check, check_flag, finish

USE = {
    "cite-only": "Read and cite. Summarise in your own words; do not reproduce the text.",
    "check-terms": "Reuse terms not yet confirmed. Treat as read and cite only.",
    "ogl-v3": "Quote and reuse with attribution under the Open Government Licence v3.0.",
    "cc-by-4.0": "Quote and reuse with attribution under CC BY 4.0.",
    "public-domain": "Quote and reuse freely.",
}
check, problems = check_flag(), []
items = sources()
per_skill = collections.defaultdict(list)
all_skills = skills()
for s in items:
    targets = {f"{k['department']}:{k['folder']}" for k in all_skills if k["department"] in s.get("departments", [])}
    targets |= set(s.get("skills", []))
    for t in targets:
        per_skill[t].append(s)

for k in all_skills:
    ref = f"{k['department']}:{k['folder']}"
    rel = k["path"].replace("SKILL.md", "references/sources.md")
    entries = sorted(per_skill.get(ref, []), key=lambda s: s["title"].lower())
    lines = [f"# Sources for `{ref}`", "",
             "Generated by `scripts/build-sources.py` from `sources/*.toml`. Do not edit by hand.", ""]
    if not entries:
        lines += ["No external sources are catalogued for this skill yet. Check current Microsoft Learn documentation",
                  "before stating how a feature behaves, and propose a source in `sources/` if one settles the question.", ""]
    for s in entries:
        lines += [f"## {s['title']}", "", f"- Publisher: {s['publisher']} ({s['jurisdiction']})", f"- Link: {s['url']}",
                  f"- Authoritative for: {s['authoritative_for']}", f"- What you may do: {USE[s['licence']]}",
                  f"- Last checked: {s['checked']}", ""]
    write_or_check(rel, "\n".join(lines), check, problems)

index = ["# Sources", "", "Every outside authority the skills check against, what it settles, and what you may do with it.",
         "Generated by `scripts/build-sources.py` from `sources/*.toml`. Do not edit by hand.", "",
         f"{len(items)} sources serving {len(per_skill)} skills.", "",
         "| Source | Publisher | Licence | Authoritative for | Departments |", "|---|---|---|---|---|"]
for s in sorted(items, key=lambda s: (s["publisher"], s["title"])):
    index.append(f"| [{s['title']}]({s['url']}) | {s['publisher']} | `{s['licence']}` | {s['authoritative_for']} | "
                 + ", ".join(f"`{d}`" for d in s["departments"]) + " |")
index += ["", "Licence meanings are defined in [`sources/README.md`](../sources/README.md).", ""]
write_or_check("docs/SOURCES.md", "\n".join(index), check, problems)
finish("skill source files", problems, len(all_skills))
