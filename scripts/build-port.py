#!/usr/bin/env python3
"""Emit every manifest and each department README from catalogue/departments.toml. --check verifies.

Claude Code reads plugins/<id>/.claude-plugin/plugin.json and .claude-plugin/marketplace.json.
ChatGPT and Codex read plugins/<id>/.codex-plugin/plugin.json and .agents/plugins/marketplace.json.
The skills are identical in both; only these manifests differ, so a fix to a skill reaches both at once.
"""
import json
from _common import (departments, skills, write_or_check, check_flag, finish, REPO_URL, MARKETPLACE,
                     DISPLAY_NAME, AUTHOR_LINE, VERSION, LAYERS, CONTENT_LICENCE, AUTHORS)

check, problems = check_flag(), []
author = {"name": AUTHOR_LINE, "url": REPO_URL}
all_skills = skills()
claude_plugins, codex_plugins = [], []


def dump(obj) -> str:
    return json.dumps(obj, indent=2, ensure_ascii=False) + "\n"


for d in departments():
    did = d["id"]
    keywords = ["dynamics-365", "crm"] + d["keywords"]
    claude = {"name": did, "description": d["description"], "version": VERSION, "author": author,
              "homepage": REPO_URL, "repository": REPO_URL, "license": CONTENT_LICENCE, "keywords": keywords}
    codex = {"name": did, "version": VERSION, "description": d["description"], "author": author,
             "homepage": REPO_URL, "repository": REPO_URL, "license": CONTENT_LICENCE, "keywords": keywords, "skills": "./skills/",
             "interface": {"displayName": d["title"], "category": "Productivity",
                           "shortDescription": f"{d['title']}, as an installable CRM delivery department",
                           "longDescription": d["description"], "developerName": AUTHOR_LINE}}
    write_or_check(f"plugins/{did}/.claude-plugin/plugin.json", dump(claude), check, problems)
    write_or_check(f"plugins/{did}/.codex-plugin/plugin.json", dump(codex), check, problems)
    claude_plugins.append({"name": did, "source": f"./plugins/{did}", "description": d["description"], "version": VERSION,
                           "author": author, "keywords": keywords, "category": d["layer"]})
    codex_plugins.append({"name": did, "source": {"source": "local", "path": f"./plugins/{did}"},
                          "policy": {"installation": "AVAILABLE"}, "category": "Productivity"})

    mine = [s for s in all_skills if s["department"] == did]
    lines = [f"# {d['title']}", "",
             "<!-- Generated by scripts/build-port.py from catalogue/departments.toml and the skills folder. Do not edit by hand. -->", "",
             d["description"], "",
             "| | |", "|---|---|",
             f"| Layer | {LAYERS[d['layer']]}{' (reviewer-class)' if d['reviewer'] else ''} |",
             f"| Lead role modelled | {d['lead_role']} |",
             f"| Subject lead | {d['subject_lead']} |",
             f"| Agent charter | [`.claude/agents/{did}.md`](../../.claude/agents/{did}.md) |", "",
             "## Install", "", "Claude Code:", "", "```", f"/plugin marketplace add SimonFoote-greensparx/{MARKETPLACE}",
             f"/plugin install {did}@{MARKETPLACE}", "```", "",
             "ChatGPT and Codex: add this repository as a plugin marketplace, or copy this folder into `.agents/skills/` in your project.", ""]
    if d["reviewer"]:
        lines += ["## Reviewer-class", "",
                  "This department also reviews what other departments build. It holds no write surface in that capacity,",
                  "and its blocking findings are not overruled by the department under review. Disagreement escalates to the",
                  "executive sponsor or steering committee.", ""]
    lines += ["## Skills", "", "| Skill | What it covers | Status |", "|---|---|---|"]
    for s in mine:
        lines.append(f"| [`{did}:{s['folder']}`](skills/{s['folder']}/SKILL.md) | {s['description']} | {s['meta'].get('status', '?')} |")
    if not mine:
        lines.append("| | No skills yet. | |")
    names = " and ".join(f"[{a['name']}]({a['url']})" for a in AUTHORS)
    lines += ["", "## Credit and licence", "",
              f"Created by {names} as part of [{DISPLAY_NAME}]({REPO_URL}). The skills are licensed under",
              "[CC BY 4.0](https://creativecommons.org/licenses/by/4.0/): use them freely, including commercially, and credit",
              f"Simon Foote and Robert Peledie when you share or adapt them. [NOTICE.md]({REPO_URL}/blob/main/NOTICE.md) gives the wording.", ""]
    write_or_check(f"plugins/{did}/README.md", "\n".join(lines), check, problems)

claude_market = {"name": MARKETPLACE, "owner": author,
                 "metadata": {"description": f"{DISPLAY_NAME}: a Dynamics 365 CE delivery team as installable departments. "
                                             "Install only the departments your project needs.", "version": VERSION},
                 "plugins": claude_plugins}
codex_market = {"name": MARKETPLACE, "interface": {"displayName": DISPLAY_NAME}, "plugins": codex_plugins}
write_or_check(".claude-plugin/marketplace.json", dump(claude_market), check, problems)
write_or_check(".agents/plugins/marketplace.json", dump(codex_market), check, problems)
finish("manifests", problems, len(claude_plugins))
