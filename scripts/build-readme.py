def author_table(photo_px: int) -> list[str]:
    """One row per author: photo, name, headline, background summary, role on the project and LinkedIn link.
    HTML rather than Markdown so the photo sits beside the text on GitHub."""
    e = html.escape
    rows = ["<table>"]
    for a in AUTHORS:
        bio = "".join(f"<p>{e(p)}</p>" for p in a["bio"])
        rows.append(f'<tr><td width="{photo_px + 20}" valign="top"><img src="{e(a["photo"])}" alt="Photo of {e(a["name"])}" '
                    f'width="{photo_px}"></td><td valign="top"><strong>{e(a["name"])}</strong><br><em>{e(a["headline"])}</em>'
                    f'{bio}<p><strong>On this project:</strong> {e(a["project_role"])}</p>'
                    f'<p><a href="{e(a["url"])}">LinkedIn profile</a></p></td></tr>')
    rows.append("</table>")
    return rows


def table(layer: str) -> list[str]:
    rows = ["| Department | Lead role modelled | Skills | Subject lead |", "|---|---|---|---|"]
    for d in depts:
        if d["layer"] == layer:
            rows.append(f"| [{d['title']}](plugins/{d['id']}/README.md) | {d['lead_role']} | {by_dept[d['id']]} | {d['subject_lead']} |")
    return rows


