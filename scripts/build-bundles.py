#!/usr/bin/env python3
"""Bundle the shared files the project-tailoring skills read into each skill's references/ folder. --check verifies.

An installed plugin (Claude Code, ChatGPT, Codex or Copilot Cowork) contains only its own folder, so the role catalogue,
combination rules, skills vocabulary, profile schema and templates must travel with the skills that read them. The
originals in data/, profiles/ and templates/ are the source of truth; these copies are regenerated, never hand-edited.

The TOML data files are bundled as JSON, because Microsoft 365 Copilot (and so Copilot Cowork) rejects a skill folder
that contains a file type it does not support, and .toml is not on its list (D21). The header comments that explain
each file's fields are carried over as an "about" field. Stale bundled files are removed.
"""
import glob, json, os, tomllib
from _common import path, write_or_check, check_flag, finish

SKILL = "plugins/project-tailoring/skills/{}/references/{}"
BUNDLES = {
    "profile-intake": {"profile-schema.json": "profiles/schema.json", "skills-vocabulary.json": "data/skills-vocabulary.toml",
                       "sample-smb-profile.yaml": "profiles/samples/smb-sample.yaml",
                       "sample-enterprise-profile.yaml": "profiles/samples/enterprise-sample.yaml"},
    "edition-selection": {"role-catalogue.json": "data/role-catalogue.toml"},
    "role-mapping": {"role-catalogue.json": "data/role-catalogue.toml", "role-combinations.json": "data/role-combinations.toml",
                     "skills-vocabulary.json": "data/skills-vocabulary.toml"},
    "skills-gap-analysis": {"role-catalogue.json": "data/role-catalogue.toml", "skills-vocabulary.json": "data/skills-vocabulary.toml"},
    "document-pack": {"role-catalogue.json": "data/role-catalogue.toml"},
    "pack-refresh": {"role-catalogue.json": "data/role-catalogue.toml", "role-combinations.json": "data/role-combinations.toml"},
}
for t in sorted(glob.glob(path("templates", "*.md"))):
    BUNDLES["document-pack"][f"templates/{os.path.basename(t)}"] = f"templates/{os.path.basename(t)}"

check, problems, count = check_flag(), [], 0


def bundled_content(src: str, dest: str) -> str:
    """The text of a bundled copy: the original, or for TOML bundled as JSON, a faithful JSON rendering."""
    text = open(path(src), encoding="utf-8").read()
    if not (src.endswith(".toml") and dest.endswith(".json")):
        return text
    about = []
    for line in text.splitlines():
        if not line.startswith("#"):
            break
        line = line.lstrip("#").strip()
        if line:
            about.append(line)
    data = {"about": " ".join(about), "generated_from": src}
    data.update(tomllib.loads(text))
    return json.dumps(data, indent=2, ensure_ascii=False, default=str) + "\n"


for skill, files in BUNDLES.items():
    if not os.path.isdir(path("plugins", "project-tailoring", "skills", skill)):
        problems.append(f"project-tailoring:{skill} does not exist")
        continue
    if len(files) + 1 > 20:
        problems.append(f"project-tailoring:{skill} would bundle more than 20 companion files (Copilot Cowork's limit)")
    lines = [f"# Bundled files for `project-tailoring:{skill}`", "",
             "Generated by `scripts/build-bundles.py`. These are copies; edit the originals and regenerate. The TOML data",
             "files are bundled as JSON with the same fields, because Microsoft 365 Copilot does not accept .toml files in a",
             "skill folder. Each JSON copy starts with an `about` field explaining its fields.", "",
             "| Bundled copy | Original in the repository |", "|---|---|"]
    for dest, src in sorted(files.items()):
        write_or_check(SKILL.format(skill, dest), bundled_content(src, dest), check, problems)
        lines.append(f"| `references/{dest}` | `{src}` |")
        count += 1
    write_or_check(SKILL.format(skill, "BUNDLED.md"), "\n".join(lines) + "\n", check, problems)
    # Remove bundled copies that are no longer expected, such as the .toml files bundled before D21.
    refs = path("plugins", "project-tailoring", "skills", skill, "references")
    keep = set(files) | {"BUNDLED.md", "sources.md"}
    for f in sorted(glob.glob(os.path.join(refs, "**", "*"), recursive=True)):
        rel = os.path.relpath(f, refs).replace(os.sep, "/")
        if os.path.isfile(f) and rel not in keep:
            if check:
                problems.append(f"project-tailoring:{skill}: stale bundled file references/{rel}; run scripts/build-bundles.py")
            else:
                os.remove(f)
finish("bundled tailoring files", problems, count)
